class ShadePointsModel:
    @classmethod
    def list_all(
        cls,
        kind: str | None = None,
        subtipo: str | None = None,
        neighborhood: str | None = None,
        region: str | None = None,
        city: str | None = None,
    ) -> list[dict]:
        pontos = VERIFIED_POINTS
        if kind:
            pontos = [p for p in pontos if p["tipo"].lower() == kind.lower()]
        if subtipo:
            pontos = [p for p in pontos if p.get("subtipo", "").lower() == subtipo.lower()]
        if neighborhood:
            pontos = [p for p in pontos if neighborhood.casefold() in p.get("bairro", "").casefold()]
        if region:
            pontos = [p for p in pontos if region.casefold() in p.get("regiao", "").casefold()]
        if city:
            pontos = [p for p in pontos if city.casefold() in p.get("cidade", "").casefold()]

        return [
            {**point, "status": "Ponto Ativo de Sombra e Conforto Térmico"}
            for point in pontos
        ]

